/**
 * manual-controlled-pipeline-check.ts — OPT-IN real Docker harness for the integrated CONTROLLED
 * fixture pipeline (offline npm ci + build + test in one disposable container). NOT production
 * wiring and NOT yet run by its author: every behaviour below is UNVERIFIED until an operator runs
 * it and logs the output in .kiro/PROJECT.md and backend/DEVELOPMENT.md.
 *
 * Skipped unless GRAVEYARD_MANUAL_CONTROLLED_PIPELINE=1, so `pnpm test` never touches Docker.
 *
 * Operator-supplied inputs (the harness FAILS CLOSED without them; values are never invented):
 *
 *   GRAVEYARD_NPM_FIXTURE_DIR  absolute path of a directory with package.json + package-lock.json
 *                              for the single dependency is-number@7.0.0 (each file <= 64 KiB, which
 *                              is the harness limit; registry-form lock with real sha512 integrity;
 *                              passes npm-lock-policy.ts). Only these two files are read.
 *   GRAVEYARD_NPM_CACHE_DIR    absolute path of an npm cache prepopulated for exactly that lockfile
 *                              (for example `npm ci --cache <dir>` run once, online, by the
 *                              operator on their own machine). Mounted read-only, never written.
 *
 * The build.mjs and test.mjs files are generated by controlled-pipeline-fixtures.ts (trusted,
 * no network, no child processes, no install scripts). The compiled driver is the sibling
 * fixture-pipeline-driver.js in dist-test/ (run `pnpm run build:test` first).
 *
 * Cases (each in its own container where one is created; network none everywhere):
 *  1. pass        is-number fixture, build + 3 tests         expect success, count == lock count
 *  2. no-tests    same, no test.mjs                           expect not-run tests-not-run, test stage not-run
 *  3. fail-build  build throws                                expect failure build-failed
 *  4. fail-test   one assertion fails                         expect failure test-failed
 *  5. cache-miss  registry-form lock, package not in cache    expect failure install-failed
 *  6. git-dep     lock resolved from git                      expect not-run policy-rejected, no container
 *  7. cancel      pre-aborted signal                          expect not-run aborted, no container
 *
 * For every container it requires confirmed cleanup, an empty staging directory afterwards and an
 * independent `docker ps -a` query showing no container from this run. Generated directories are
 * removed with removeRunDir. Mid-run timeout and cancel are covered only by the mock tests.
 *
 * A pass shows only that these fixtures behaved as expected on this machine with this Docker, image
 * and cache. It says nothing about arbitrary repositories, hostile packages, or the strength of the
 * policy. Assumptions that may make a first run fail closed: npm's `added N packages` line,
 * `npm ci --offline` succeeding with a read-only cache, node and npm running on noexec tmpfs mounts
 * as uid 65532, `node --test` working with a read-only root, Docker Desktop reporting bind sources
 * in the host form, the 64 MiB /work tmpfs being large enough.
 *
 * Run (outside the restricted sandbox):
 *   pnpm run build:test
 *   $env:GRAVEYARD_MANUAL_CONTROLLED_PIPELINE = "1"
 *   $env:GRAVEYARD_NPM_FIXTURE_DIR = "C:\path\to\is-number7-fixture"
 *   $env:GRAVEYARD_NPM_CACHE_DIR = "C:\path\to\npm-cache"
 *   node --test dist-test/test/manual-controlled-pipeline-check.js
 */

import { randomBytes } from "node:crypto";
import { lstatSync, readFileSync, readdirSync, realpathSync, type Stats } from "node:fs";
import { test } from "node:test";
import { dirname, isAbsolute, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { ControlledPipeline, type ControlledPipelineResult, type PipelineReason, type PipelineVerdict } from "../controlled-pipeline.js";
import { pipelineFixtureScripts, type PipelineFixtureKind } from "../controlled-pipeline-fixtures.js";
import { spawnExecutor } from "../docker-sandbox.js";
import { createRunDir, ensureOwnedParent, removeRunDir, writeFixture } from "../fixture-workspace.js";
import { NODE_FIXTURE_IMAGE } from "../node-fixture-runner.js";

const OPT_IN = process.env["GRAVEYARD_MANUAL_CONTROLLED_PIPELINE"] === "1";
const MAX_FILE = 64 * 1024;

class FailClosed extends Error {}

interface Expectation { status: PipelineVerdict; reason: PipelineReason; container: boolean }

function describeResult(r: ControlledPipelineResult): string {
  const cl = r.cleanup === null ? "none" : r.cleanup.confirmed ? "confirmed" : `UNCONFIRMED(${r.cleanup.reason})`;
  const stages = r.stages === null ? "no-report" : r.stages.map((s) => `${s.stage}:${s.status}`).join(",");
  return `${r.status} (${r.reason}) failedStage=${String(r.failedStage)} exit=${String(r.exitCode)} ` +
    `added=${String(r.packagesAdded)}/${String(r.expectedPackages)} truncated=${String(r.truncated)} ` +
    `cleanup=${cl} stagingRemoved=${String(r.stagingRemoved)} stages=[${stages}]`;
}

async function dockerQuery(args: readonly string[]): Promise<{ ok: boolean; stdout: string }> {
  try {
    const r = await spawnExecutor("docker", args, { timeoutMs: 20_000, maxOutputBytes: 64 * 1024 });
    return { ok: r.exitCode === 0 && !r.timedOut && !r.truncated, stdout: r.stdout };
  } catch {
    return { ok: false, stdout: "" };
  }
}

function backendRoot(): string {
  const root = resolve(dirname(fileURLToPath(import.meta.url)), "..", "..");
  let name: unknown;
  try {
    name = (JSON.parse(readFileSync(join(root, "package.json"), "utf8")) as { name?: unknown }).name;
  } catch {
    throw new FailClosed(`cannot read package.json at the expected backend root ${root}`);
  }
  if (name !== "graveyard-backend") throw new FailClosed(`${root} is not the graveyard-backend package`);
  return realpathSync(root);
}

function requireAbsoluteDir(envName: string): string {
  const v = process.env[envName];
  if (v === undefined || v === "") throw new FailClosed(`${envName} is not set; the harness needs an operator-supplied controlled input`);
  if (!isAbsolute(v)) throw new FailClosed(`${envName} must be an absolute path`);
  let real: string;
  try {
    real = realpathSync(v);
    if (!lstatSync(real).isDirectory()) throw new Error("not a directory");
  } catch {
    throw new FailClosed(`${envName} does not point to an existing directory`);
  }
  return real;
}

function readOperatorFile(dir: string, name: string): string {
  const p = join(dir, name);
  let st: Stats;
  try {
    st = lstatSync(p);
  } catch {
    throw new FailClosed(`${name} is missing from the operator fixture directory`);
  }
  if (!st.isFile() || st.size > MAX_FILE) throw new FailClosed(`${name} must be a regular file of at most ${MAX_FILE} bytes`);
  return readFileSync(p, "utf8");
}

const UNCACHED_INTEGRITY = `sha512-${"B".repeat(86)}==`;
const UNCACHED_PACKAGE = JSON.stringify({
  name: "gy-uncached", version: "1.0.0", private: true, dependencies: { "graveyard-uncached-fixture": "1.0.0" },
}, null, 2) + "\n";
const UNCACHED_LOCK = JSON.stringify({
  name: "gy-uncached", version: "1.0.0", lockfileVersion: 3, requires: true,
  packages: {
    "": { name: "gy-uncached", version: "1.0.0", dependencies: { "graveyard-uncached-fixture": "1.0.0" } },
    "node_modules/graveyard-uncached-fixture": {
      version: "1.0.0",
      resolved: "https://registry.npmjs.org/graveyard-uncached-fixture/-/graveyard-uncached-fixture-1.0.0.tgz",
      integrity: UNCACHED_INTEGRITY,
    },
  },
}, null, 2) + "\n";
const GIT_LOCK = UNCACHED_LOCK.replace(
  "https://registry.npmjs.org/graveyard-uncached-fixture/-/graveyard-uncached-fixture-1.0.0.tgz",
  "git+https://github.com/example/example.git#0000000000000000000000000000000000000000",
);

test(
  "manual controlled fixture pipeline harness (opt-in: GRAVEYARD_MANUAL_CONTROLLED_PIPELINE=1)",
  { skip: OPT_IN ? false : "set GRAVEYARD_MANUAL_CONTROLLED_PIPELINE=1 to run against real Docker", timeout: 900_000 },
  async () => {
    const runId = randomBytes(5).toString("hex");
    const log: string[] = [];
    const problems: string[] = [];
    let parent: string | undefined;
    let fixturesDir: string | undefined;
    let stagingDir: string | undefined;
    let failure: unknown;

    try {
      const fixtureSrc = requireAbsoluteDir("GRAVEYARD_NPM_FIXTURE_DIR");
      const cacheDir = requireAbsoluteDir("GRAVEYARD_NPM_CACHE_DIR");
      if (readdirSync(cacheDir).length === 0) throw new FailClosed("GRAVEYARD_NPM_CACHE_DIR is empty; it must be prepopulated");
      const goodPkg = readOperatorFile(fixtureSrc, "package.json");
      const goodLock = readOperatorFile(fixtureSrc, "package-lock.json");
      if (!goodLock.includes('"node_modules/is-number"')) {
        throw new FailClosed("the operator lockfile does not contain node_modules/is-number; the generated scripts need it");
      }

      const v = await dockerQuery(["version", "--format", "{{.Server.Version}}"]);
      if (!v.ok || v.stdout.trim() === "") throw new FailClosed("docker daemon is not available");
      log.push(`docker server ${v.stdout.trim()}`);
      const img = await dockerQuery(["image", "inspect", "--format", "{{.Id}}", NODE_FIXTURE_IMAGE]);
      if (!img.ok) throw new FailClosed(`image ${NODE_FIXTURE_IMAGE} must already exist locally (never pulled)`);

      parent = ensureOwnedParent(backendRoot());
      fixturesDir = createRunDir(parent);
      stagingDir = createRunDir(parent);

      const withScripts = (kind: PipelineFixtureKind, pkg: string, lock: string): Record<string, string> =>
        ({ "package.json": pkg, "package-lock.json": lock, ...pipelineFixtureScripts(kind) });
      writeFixture(fixturesDir, "pass", withScripts("pass", goodPkg, goodLock));
      writeFixture(fixturesDir, "no-tests", withScripts("no-tests", goodPkg, goodLock));
      writeFixture(fixturesDir, "fail-build", withScripts("fail-build", goodPkg, goodLock));
      writeFixture(fixturesDir, "fail-test", withScripts("fail-test", goodPkg, goodLock));
      writeFixture(fixturesDir, "cache-miss", withScripts("pass", UNCACHED_PACKAGE, UNCACHED_LOCK));
      writeFixture(fixturesDir, "git-dep", withScripts("pass", UNCACHED_PACKAGE, GIT_LOCK));
      log.push(`generated fixtures under ${fixturesDir}; staging under ${stagingDir}`);

      const pipeline = new ControlledPipeline({
        executor: spawnExecutor, fixturesRoot: fixturesDir, stagingRoot: stagingDir, cacheDir,
      });
      const cases: Array<{ fixture: string; want: Expectation; abort?: boolean; stages?: string }> = [
        { fixture: "pass", want: { status: "success", reason: "ok", container: true }, stages: "passed,passed,passed,passed" },
        { fixture: "no-tests", want: { status: "not-run", reason: "tests-not-run", container: true }, stages: "passed,passed,passed,not-run" },
        { fixture: "fail-build", want: { status: "failure", reason: "build-failed", container: true }, stages: "passed,passed,failed,skipped" },
        { fixture: "fail-test", want: { status: "failure", reason: "test-failed", container: true }, stages: "passed,passed,passed,failed" },
        { fixture: "cache-miss", want: { status: "failure", reason: "install-failed", container: true }, stages: "passed,failed,skipped,skipped" },
        { fixture: "git-dep", want: { status: "not-run", reason: "policy-rejected", container: false } },
        { fixture: "pass", want: { status: "not-run", reason: "aborted", container: false }, abort: true },
      ];
      let n = 0;
      for (const c of cases) {
        n += 1;
        const ac = new AbortController();
        if (c.abort === true) ac.abort();
        const r = await pipeline.run({ executionId: `pipefix-${runId}-${n}:1`, fixture: c.fixture, signal: ac.signal });
        const label = `[${n}:${c.fixture}${c.abort === true ? " pre-aborted" : ""}]`;
        log.push(`${label} ${describeResult(r)}`);
        if (r.stderrTail !== "") log.push(`${label} container stderr tail: ${r.stderrTail.slice(-400)}`);
        for (const s of r.stages ?? []) {
          if (s.status === "failed" && s.stderrTail) log.push(`${label} ${s.stage} stderr tail: ${s.stderrTail.slice(-300)}`);
        }
        if (r.status !== c.want.status) problems.push(`${label} status ${r.status}, expected ${c.want.status}`);
        if (r.reason !== c.want.reason) problems.push(`${label} reason ${r.reason}, expected ${c.want.reason}`);
        if (c.want.container && r.cleanup === null) problems.push(`${label} expected a container but no cleanup proof`);
        if (!c.want.container && r.cleanup !== null) problems.push(`${label} no container expected but a cleanup proof exists`);
        if (r.cleanup !== null && !r.cleanup.confirmed) problems.push(`${label} container cleanup not confirmed`);
        if (r.stagingRemoved === false) problems.push(`${label} staging directory not removed`);
        if (c.stages !== undefined && r.stages?.map((s) => s.status).join(",") !== c.stages) {
          problems.push(`${label} stage statuses differ from ${c.stages}`);
        }
        if (c.want.status === "success" && r.packagesAdded !== r.expectedPackages) problems.push(`${label} added count differs from the lock`);
      }

      if (readdirSync(stagingDir).length !== 0) problems.push("staging directory is not empty after the run");
      const left = await dockerQuery(["ps", "--all", "--quiet", "--no-trunc", "--filter", `name=graveyard-pipefix-${runId}`]);
      if (!left.ok) problems.push("could not query leftover containers");
      else if (left.stdout.trim() !== "") problems.push(`containers left from this run: ${left.stdout.trim()}`);
      else log.push("independent docker ps: no containers left from this run");
    } catch (e) {
      failure = e;
    } finally {
      if (parent !== undefined) {
        for (const d of [fixturesDir, stagingDir]) {
          if (d === undefined) continue;
          const r = removeRunDir(parent, d);
          if (r.removed) log.push(`removed ${d}`);
          else problems.push(...r.problems.map((p) => `removal: ${p}`));
        }
      }
      for (const l of log) console.log(`INFO  ${l}`);
      if (problems.length > 0) console.log(`PROBLEMS:\n${problems.join("\n")}`);
      if (failure instanceof FailClosed) {
        console.log(`FAIL-CLOSED: ${failure.message}\nNo claim is made about the pipeline, npm or Docker behaviour.`);
      }
    }
    if (failure !== undefined) throw failure;
    if (problems.length > 0) throw new Error(`controlled pipeline harness found ${problems.length} problem(s)`);
  },
);
